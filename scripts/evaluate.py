"""
Evaluate RoadWatch AI on data it never saw during training.

Produces (in results/):
  metrics_test.csv        per-class precision, recall, F1, mAP@0.5, mAP@0.5:0.95 on the test set
  metrics_unseen.csv      same, on the held-out country (if prepared)
  det_vs_seg.csv          pothole detection model vs segmentation model on the same pothole test images
  metrics_seg_test.csv    segmentation (pothole + crack outlines) per-class mask metrics
  summary.md              all tables in Markdown (paste into README)
  confusion_matrix_*.png, PR_curve_*.png

Example:
    python scripts/evaluate.py
"""
import argparse
import csv
import shutil
from pathlib import Path

from ultralytics import YOLO

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"


def f1(p, r):
    return 2 * p * r / (p + r) if (p + r) else 0.0


def cls_result(metric, ap_class_index, cls):
    """(precision, recall, mAP50, mAP50-95) for one class id, zeros if absent."""
    idx = list(int(c) for c in ap_class_index)
    return metric.class_result(idx.index(cls)) if cls in idx else (0.0, 0.0, 0.0, 0.0)


def per_class_table(metrics):
    rows = []
    box = metrics.box
    for i, c in enumerate(metrics.ap_class_index):
        p, r, ap50, ap = box.class_result(i)
        rows.append(dict(cls=metrics.names[int(c)], precision=p, recall=r, f1=f1(p, r), mAP50=ap50, mAP50_95=ap))
    rows.append(dict(cls="ALL", precision=box.mp, recall=box.mr, f1=f1(box.mp, box.mr),
                     mAP50=box.map50, mAP50_95=box.map))
    return rows


def save_rows(rows, name):
    path = RES / f"{name}.csv"
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    return path


def to_markdown(rows, title):
    keys = list(rows[0].keys())
    out = [f"### {title}", "", "| " + " | ".join(keys) + " |", "|" + "---|" * len(keys)]
    for r in rows:
        out.append("| " + " | ".join(f"{v:.3f}" if isinstance(v, float) else str(v) for v in r.values()) + " |")
    return "\n".join(out) + "\n"


def copy_plots(save_dir, tag):
    for fname in ("confusion_matrix_normalized.png", "confusion_matrix.png", "BoxPR_curve.png", "PR_curve.png"):
        src = Path(save_dir) / fname
        if src.exists():
            shutil.copy2(src, RES / f"{src.stem}_{tag}.png")


def run_val(model, data, tag, device, imgsz):
    m = model.val(data=data, split="test", device=device, imgsz=imgsz, plots=True,
                  project=str(ROOT / "runs" / "eval"), name=tag, exist_ok=True, verbose=False)
    copy_plots(m.save_dir, tag)
    return m


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--det", default=str(ROOT / "weights" / "roadwatch_det.pt"))
    ap.add_argument("--seg", default=str(ROOT / "weights" / "roadwatch_seg.pt"))
    ap.add_argument("--device", default="0")
    ap.add_argument("--imgsz", type=int, default=640)
    args = ap.parse_args()
    RES.mkdir(exist_ok=True)
    md = ["## Results (generated by scripts/evaluate.py)\n"]

    det = YOLO(args.det)
    print("== Test set (never used in training) ==")
    rows = per_class_table(run_val(det, str(ROOT / "configs" / "roadwatch_det.yaml"), "test", args.device, args.imgsz))
    save_rows(rows, "metrics_test")
    md.append(to_markdown(rows, "Test set: per-class detection performance"))

    for unseen_yaml in sorted((ROOT / "configs").glob("unseen_*.yaml")):
        country = unseen_yaml.stem.replace("unseen_", "")
        print(f"== Unseen country: {country} ==")
        rows = per_class_table(run_val(det, str(unseen_yaml), unseen_yaml.stem, args.device, args.imgsz))
        save_rows(rows, "metrics_unseen")
        md.append(to_markdown(rows, f"Unseen country ({country}, never in training)"))

    pothole_det_yaml = ROOT / "configs" / "pothole_test_det.yaml"
    pothole_seg_yaml = ROOT / "configs" / "pothole_test_seg.yaml"
    if Path(args.seg).exists() and pothole_det_yaml.exists() and pothole_seg_yaml.exists():
        print("== Detection vs segmentation (identical pothole test images) ==")
        d = run_val(det, str(pothole_det_yaml), "pothole_det", args.device, args.imgsz)
        dp, dr, d50, d5095 = cls_result(d.box, d.ap_class_index, 3)
        s = run_val(YOLO(args.seg), str(pothole_seg_yaml), "pothole_seg", args.device, args.imgsz)
        sbp, sbr, sb50, sb5095 = cls_result(s.box, s.ap_class_index, 0)
        smp, smr, sm50, sm5095 = cls_result(s.seg, s.ap_class_index, 0)
        rows = [
            dict(model="Detection (box)", precision=dp, recall=dr, f1=f1(dp, dr), mAP50=d50, mAP50_95=d5095),
            dict(model="Segmentation (box)", precision=sbp, recall=sbr, f1=f1(sbp, sbr), mAP50=sb50, mAP50_95=sb5095),
            dict(model="Segmentation (mask)", precision=smp, recall=smr, f1=f1(smp, smr), mAP50=sm50, mAP50_95=sm5095),
        ]
        save_rows(rows, "det_vs_seg")
        md.append(to_markdown(rows, "Detection vs segmentation on the same pothole test images"))

    seg_yaml = ROOT / "configs" / "roadwatch_seg.yaml"
    if Path(args.seg).exists() and seg_yaml.exists():
        print("== Segmentation model: test set (potholes + cracks) ==")
        s = run_val(YOLO(args.seg), str(seg_yaml), "seg_test", args.device, args.imgsz)
        rows = []
        for i, c in enumerate(s.ap_class_index):
            mp, mr, m50, m5095 = s.seg.class_result(i)
            rows.append(dict(cls=s.names[int(c)], mask_precision=mp, mask_recall=mr, mask_f1=f1(mp, mr),
                             mask_mAP50=m50, mask_mAP50_95=m5095))
        if rows:
            save_rows(rows, "metrics_seg_test")
            md.append(to_markdown(rows, "Segmentation test set: pixel outlines per class"))

    (RES / "summary.md").write_text("\n".join(md))
    print("\n" + "\n".join(md))
    print("Saved tables and plots to results/")


if __name__ == "__main__":
    main()
